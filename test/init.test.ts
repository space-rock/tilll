import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { parseConfig } from "../src/config.js";
import { InitError, initEnv } from "../src/init.js";
import { thrownBy } from "./helpers/failure.js";

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

const EXAMPLE = readFileSync(new URL("../.env.example", import.meta.url), "utf8");

/** A folder holding the repo's own .env.example, as a fresh clone would. */
function clone(env?: string) {
  const dir = mkdtempSync(join(tmpdir(), "tilll-init-"));
  dirs.push(dir);
  writeFileSync(join(dir, ".env.example"), EXAMPLE);
  if (env !== undefined) writeFileSync(join(dir, ".env"), env);
  return dir;
}

/** The values in a .env text (the part before any inline comment). */
function valuesOf(text: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const match = /^([A-Z_]+)=(\S*)/.exec(line);
    if (match) values[match[1]!] = match[2]!;
  }
  return values;
}

/** Deterministic "randomness", different on every call. */
function counter() {
  let n = 0;
  return (bytes: number) => Buffer.alloc(bytes, ++n);
}

const read = (dir: string) => readFileSync(join(dir, ".env"), "utf8");

/** `init` on a new clone with real randomness; the values it wrote. */
function freshRun() {
  const dir = clone();
  initEnv({ dir });
  return valuesOf(read(dir));
}

describe("tilll init", () => {
  it("makes .env from .env.example, with a merchant secret and a webhook secret", () => {
    const dir = clone();

    const result = initEnv({ dir, random: counter() });

    expect(result.created).toBe(true);
    const values = valuesOf(read(dir));
    expect(values.MERCHANT_SECRET).toMatch(/^sk_live_[0-9a-f]{48}$/);
    expect(values.WEBHOOK_SECRET).toMatch(/^whsec_[0-9a-f]{48}$/);
    expect(result.filled).toEqual(["MERCHANT_SECRET", "WEBHOOK_SECRET"]);
  });

  it("makes no key: refunds are approved with a wallet, so there is no signing key to keep in .env", () => {
    const dir = clone();
    initEnv({ dir, random: counter() });
    expect(read(dir)).not.toMatch(/SETTLEMENT_PRIVATE_KEY/);
    expect(EXAMPLE).not.toMatch(/SETTLEMENT_PRIVATE_KEY/);
  });

  it("does not invent a settlement account, because it has to be one the merchant controls, and says so", () => {
    const dir = clone();

    const result = initEnv({ dir, random: counter() });

    expect(valuesOf(read(dir)).SETTLEMENT_ACCOUNT_ID).toBe("");
    expect(result.warnings.join(" ")).toMatch(/SETTLEMENT_ACCOUNT_ID is still empty/);
    expect(result.warnings.join(" ")).toMatch(/wallet/);
    expect(result.kept).toContain("SETTLEMENT_ACCOUNT_ID");
  });

  it("leaves a .env that Tilll accepts as configuration, once the account is set", () => {
    const dir = clone();
    initEnv({ dir, random: counter() });
    const env = { ...valuesOf(read(dir)), SETTLEMENT_ACCOUNT_ID: "shop-pay.near" };
    expect(() => parseConfig(env)).not.toThrow();
    // Without an account it refuses to start, naming the setting.
    expect(() => parseConfig(valuesOf(read(dir)))).toThrow(/SETTLEMENT_ACCOUNT_ID/);
  });

  it("makes real random secrets: no two runs, and no two settings, share a value", () => {
    const first = freshRun();
    const second = freshRun();
    expect(first.MERCHANT_SECRET).not.toBe(second.MERCHANT_SECRET);
    expect(first.WEBHOOK_SECRET).not.toBe(second.WEBHOOK_SECRET);
    expect(first.MERCHANT_SECRET!.slice("sk_live_".length)).not.toBe(first.WEBHOOK_SECRET!.slice("whsec_".length));
  });

  it("keeps the comments and every other setting exactly as they were", () => {
    const dir = clone();
    initEnv({ dir, random: counter() });
    const before = EXAMPLE.split("\n");
    const after = read(dir).split("\n");
    expect(after).toHaveLength(before.length);
    const changed = after.filter((line, i) => line !== before[i]).map((line) => line.split("=")[0]);
    expect(changed).toEqual(["MERCHANT_SECRET", "WEBHOOK_SECRET"]);
    expect(read(dir)).toMatch(/SLIPPAGE_BPS=100/);
    expect(read(dir)).toMatch(/# any public RPC/);
  });

  it("keeps an inline comment next to a value it fills", () => {
    const dir = clone();
    initEnv({ dir, random: counter() });
    expect(read(dir)).toMatch(/^MERCHANT_SECRET=sk_live_[0-9a-f]{48} +# generated by `tilll init`/m);
  });

  it("writes a .env that only its owner can read", () => {
    const dir = clone();
    initEnv({ dir, random: counter() });
    expect(statSync(join(dir, ".env")).mode & 0o777).toBe(0o600);
  });

  describe("a second run", () => {
    it("changes nothing and says every value was kept", () => {
      const dir = clone();
      initEnv({ dir, random: counter() });
      const once = read(dir);

      const again = initEnv({ dir, random: counter() });

      expect(read(dir)).toBe(once);
      expect(again.created).toBe(false);
      expect(again.filled).toEqual([]);
      expect(again.kept).toEqual(["MERCHANT_SECRET", "WEBHOOK_SECRET", "SETTLEMENT_ACCOUNT_ID"]);
    });
  });

  describe("an existing .env", () => {
    it("never replaces a secret or an account that was set by hand, and does not warn about the account", () => {
      const dir = clone(
        [`MERCHANT_SECRET=sk_live_mine`, `WEBHOOK_SECRET=whsec_mine`, `SETTLEMENT_ACCOUNT_ID=myshop.near`].join("\n") +
          "\n",
      );

      const result = initEnv({ dir, random: counter() });

      expect(valuesOf(read(dir))).toEqual({
        MERCHANT_SECRET: "sk_live_mine",
        WEBHOOK_SECRET: "whsec_mine",
        SETTLEMENT_ACCOUNT_ID: "myshop.near",
      });
      expect(result.filled).toEqual([]);
      expect(result.warnings).toEqual([]);
    });

    it("fills only what is missing, and adds a setting that is not in the file at all", () => {
      const dir = clone("PORT=9999\nMERCHANT_SECRET=sk_live_mine\n");
      const result = initEnv({ dir, random: counter() });
      const values = valuesOf(read(dir));
      expect(values.PORT).toBe("9999");
      expect(values.MERCHANT_SECRET).toBe("sk_live_mine");
      expect(values.WEBHOOK_SECRET).toMatch(/^whsec_/);
      expect(result.filled).toContain("WEBHOOK_SECRET");
    });

    it("treats an empty value and the example's placeholders as unset", () => {
      const dir = clone("MERCHANT_SECRET=sk_live_...\nWEBHOOK_SECRET=\n");
      initEnv({ dir, random: counter() });
      const values = valuesOf(read(dir));
      expect(values.MERCHANT_SECRET).toMatch(/^sk_live_[0-9a-f]{48}$/);
      expect(values.WEBHOOK_SECRET).toMatch(/^whsec_[0-9a-f]{48}$/);
    });

    it("warns, rather than guessing, when the account is still the old example name", () => {
      const dir = clone("SETTLEMENT_ACCOUNT_ID=shopname-pay.near\n");

      const result = initEnv({ dir, random: counter() });

      expect(valuesOf(read(dir)).SETTLEMENT_ACCOUNT_ID).toBe("shopname-pay.near");
      expect(result.warnings.join(" ")).toMatch(/SETTLEMENT_ACCOUNT_ID.*shopname-pay\.near/);
    });

    it("leaves an old SETTLEMENT_PRIVATE_KEY line alone: it is ignored now, and not Tilll's to delete", () => {
      const dir = clone("SETTLEMENT_PRIVATE_KEY=ed25519:abc\nSETTLEMENT_ACCOUNT_ID=myshop.near\n");
      initEnv({ dir, random: counter() });
      expect(valuesOf(read(dir)).SETTLEMENT_PRIVATE_KEY).toBe("ed25519:abc");
    });

    it("uses CRLF files and values without a trailing newline without damaging them", () => {
      const dir = clone("MERCHANT_SECRET=\r\nPORT=1\r\nWEBHOOK_SECRET=");
      initEnv({ dir, random: counter() });
      const text = read(dir);
      expect(text).toMatch(/^MERCHANT_SECRET=sk_live_[0-9a-f]{48}\r\n/);
      expect(text).toMatch(/PORT=1\r\n/);
      expect(valuesOf(text.replaceAll("\r", "")).WEBHOOK_SECRET).toMatch(/^whsec_/);
    });
  });

  it("refuses to run where there is neither a .env nor an .env.example, and says where to run it", () => {
    const dir = mkdtempSync(join(tmpdir(), "tilll-empty-"));
    dirs.push(dir);
    const error = thrownBy(InitError, () => initEnv({ dir }));
    expect(error.message).toMatch(/Tilll folder|\.env\.example/);
  });

  it("never reports a secret in its result", () => {
    const dir = clone();
    const result = initEnv({ dir, random: counter() });
    const secrets = Object.entries(valuesOf(read(dir)))
      .filter(([name]) => ["MERCHANT_SECRET", "WEBHOOK_SECRET"].includes(name))
      .map(([, value]) => value);
    for (const secret of secrets) expect(JSON.stringify(result)).not.toContain(secret);
  });
});
